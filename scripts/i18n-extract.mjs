#!/usr/bin/env node
// Scans the code for t("...") and m("...") calls and keeps the catalogue manifest
// (i18n/keys.json) and its seed SQL up to date (spec 5d).
//
//   node scripts/i18n-extract.mjs           write i18n/keys.json and supabase/seeds/translation_keys.sql
//   node scripts/i18n-extract.mjs --check   CI: fail if a key used in code is missing from the manifest,
//                                           or a message code raised by the database has no English text
import { readdirSync, readFileSync, statSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { join, relative, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) {
      if (name === "node_modules" || name === "routeTree.gen.ts") continue;
      walk(full, out);
    } else if (/\.(ts|tsx)$/.test(name) && !/\.(test|spec)\.tsx?$/.test(name) && name !== "routeTree.gen.ts") {
      out.push(full);
    }
  }
  return out;
}

const CALL = /(?<![\w.$])(?:t|m)\(\s*(?:"((?:[^"\\\n]|\\.)*)"|'((?:[^'\\\n]|\\.)*)'|`((?:[^`\\$]|\\.)*)`)/g;

function unescape(text) {
  return text.replace(/\\(["'`\\])/g, "$1").replace(/\\n/g, "\n");
}

const found = new Map(); // key -> Set(files)
for (const file of walk(join(root, "src"))) {
  const source = readFileSync(file, "utf8");
  for (const match of source.matchAll(CALL)) {
    const key = unescape(match[1] ?? match[2] ?? match[3]);
    if (!key.trim()) continue;
    if (!found.has(key)) found.set(key, new Set());
    found.get(key).add(relative(root, file).replaceAll("\\", "/"));
  }
}

const keys = [...found.entries()]
  .map(([key, files]) => ({
    key,
    context: [...files].sort()[0],
    placeholders: [...new Set([...key.matchAll(/\{(\w+)/g)].map((p) => p[1]))],
  }))
  .sort((a, b) => a.key.localeCompare(b.key));

const manifestPath = join(root, "i18n", "keys.json");
const manifest = JSON.stringify(keys, null, 2) + "\n";

// message codes the database can raise must have English text in MESSAGES
function sqlCodes() {
  const dir = join(root, "supabase", "migrations");
  if (!existsSync(dir)) return [];
  const codes = new Set();
  for (const name of readdirSync(dir)) {
    const sql = readFileSync(join(dir, name), "utf8");
    for (const m of sql.matchAll(/app_error\(\s*'([a-z_]+\.[a-z_]+)'/g)) codes.add(m[1]);
    for (const m of sql.matchAll(/raise exception '([a-z_]+\.[a-z_]+)'/g)) codes.add(m[1]);
  }
  return [...codes].sort();
}
const messagesSource = readFileSync(join(root, "src", "i18n", "messages.ts"), "utf8");
const missingCodes = sqlCodes().filter((code) => !messagesSource.includes(`"${code}"`));

if (check) {
  const committed = existsSync(manifestPath) ? JSON.parse(readFileSync(manifestPath, "utf8")) : [];
  const committedKeys = new Set(committed.map((k) => k.key));
  const missing = keys.filter((k) => !committedKeys.has(k.key));
  let failed = false;
  if (missing.length) {
    failed = true;
    console.error("Keys used in code but missing from the catalogue manifest (run `npm run i18n`):");
    for (const k of missing) console.error(`  "${k.key}"  (${k.context})`);
  }
  if (missingCodes.length) {
    failed = true;
    console.error("Database message codes without English text in src/i18n/messages.ts:");
    for (const c of missingCodes) console.error(`  ${c}`);
  }
  if (failed) process.exit(1);
  console.log(`i18n: ${keys.length} keys, all in the catalogue manifest`);
} else {
  mkdirSync(dirname(manifestPath), { recursive: true });
  writeFileSync(manifestPath, manifest);
  const q = (s) => "'" + s.replaceAll("'", "''") + "'";
  const rows = keys.map((k) => `  (${q(k.key)}, ${q(k.context)}, ${q(`{${k.placeholders.join(",")}}`)})`).join(",\n");
  const seedDir = join(root, "supabase", "seeds");
  mkdirSync(seedDir, { recursive: true });
  writeFileSync(
    join(seedDir, "translation_keys.sql"),
    `-- Generated by scripts/i18n-extract.mjs from i18n/keys.json. Do not edit.\n` +
      (keys.length
        ? `insert into public.translation_keys (key, context, placeholders) values\n${rows}\non conflict (key) do update set context = excluded.context, placeholders = excluded.placeholders;\n`
        : ""),
  );
  console.log(`i18n: wrote ${keys.length} keys`);
}
